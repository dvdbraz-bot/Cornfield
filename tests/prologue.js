const { chromium } = require('playwright');
(async () => {
  const out = process.argv[2];
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 915, height: 412 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const errs = []; p.on('pageerror', e => errs.push('PAGEERROR ' + e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  const S = (f) => p.evaluate(f);
  await p.goto('http://localhost:8123/'); await p.waitForTimeout(1200);
  await p.screenshot({ path: out + '/01-menu.png' });
  await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(800); await p.keyboard.press('1'); await p.waitForTimeout(3500);
  await p.screenshot({ path: out + '/02-rain.png' });
  await p.waitForTimeout(13000);
  await S(() => { const s = game.scene.getScene('Prologue'); s.hx = 27*16+8; s.hy = 7*16+8; });
  await p.waitForTimeout(300); await p.keyboard.press('e'); await p.waitForTimeout(2000);
  console.log('state', await S(() => game.scene.getScene('Prologue').state));
  await p.screenshot({ path: out + '/03-doze.png' });
  await p.waitForTimeout(13000);
  await S(() => { const s = game.scene.getScene('Prologue'); s.hx = 16*16+8; s.hy = 13*16+8; });
  await p.waitForTimeout(4000);
  await p.screenshot({ path: out + '/04-laugh-marker.png' });
  await S(() => { const s = game.scene.getScene('Prologue'); s.hx = 22*16+8; s.hy = 29*16+8; });
  await p.waitForTimeout(3600);
  await p.screenshot({ path: out + '/05-lure.png' });
  console.log('crickets icon level', await S(() => Controls.crickets));
  await S(() => { const s = game.scene.getScene('Prologue'); s.strike(); });
  await p.waitForTimeout(2600); await p.screenshot({ path: out + '/06-rolled.png' });
  await p.waitForTimeout(1000); await p.screenshot({ path: out + '/07-rocks-line.png' });
  await p.waitForTimeout(4600); await p.screenshot({ path: out + '/08-picked-up.png' });
  await p.waitForTimeout(3600); await p.screenshot({ path: out + '/09-hand.png' });
  await p.waitForTimeout(18000);
  console.log('scenes', await S(() => game.scene.getScenes(true).map(s => s.sys.settings.key).join(',')));
  await p.screenshot({ path: out + '/10-title.png' });
  console.log('ERRORS', errs);
  await b.close();
})();
